-- Pawtrol shared memory. Access through the server only.
create table if not exists public.animals (
  id bigint generated by default as identity primary key,
  nickname text not null,
  species text not null check (species in ('dog','cat','cow')),
  image text not null,
  hash text not null,
  colors text not null,
  location text not null,
  latitude double precision,
  longitude double precision,
  created_at timestamptz not null default now()
);
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  animal_id bigint not null references public.animals(id),
  kind text not null check (kind in ('sighting','feeding')),
  image text not null,
  location text not null,
  latitude double precision,
  longitude double precision,
  happened_at timestamptz not null,
  note text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists events_animal_time on public.events(animal_id, happened_at desc);
alter table public.animals enable row level security;
alter table public.events enable row level security;
-- No browser access policy. Server holds the service role credential.

grant select, insert on public.animals, public.events to service_role;
grant usage, select on sequence public.animals_id_seq, public.events_id_seq to service_role;
